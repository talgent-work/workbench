#!/usr/bin/env bash
set -euo pipefail

# Maintainer-only generation. Deployment consumes the checked-in YAML and does
# not require Helm, Git, chart downloads, or a Helm release.
root_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)
command -v helm >/dev/null
render_dir=$(mktemp -d)
trap 'rm -rf "$render_dir"' EXIT
# Fetch chart sources only.
chart_revision=05a8d26a18bbdf1b3e698483fa7c14a9b4d903ec
git init -q "$render_dir/source"
git -C "$render_dir/source" remote add origin https://github.com/opensandbox-group/OpenSandbox.git
git -C "$render_dir/source" fetch --depth 1 origin "$chart_revision"
git -C "$render_dir/source" checkout --detach FETCH_HEAD
test "$(git -C "$render_dir/source" rev-parse HEAD)" = "$chart_revision"
charts="$render_dir/source/kubernetes/charts"
helm template opensandbox-controller "$charts/opensandbox-controller" --namespace opensandbox-system > "$render_dir/controller.yaml"
helm template opensandbox "$charts/opensandbox-server" --namespace talgent -f "$root_dir/deploy/opensandbox/server-values.yaml" > "$render_dir/server.yaml"
# The chart grants the server a ClusterRole over Pods, Secrets and every other
# resource it manages, in any namespace. The k3s base grants it those only in
# the sandbox namespace (deploy/k3s/workbench/sandbox.yaml), so the chart's
# cluster-scoped RBAC is dropped from the server's manifest.
drop_cluster_rbac() {
  awk '
    function flush() { if (doc != "" && doc !~ /\nkind: ClusterRole(Binding)?\n/) printf "%s", doc; doc = "" }
    /^---$/ { flush() }
    { doc = doc $0 "\n" }
    END { flush() }
  '
}
drop_cluster_rbac < "$render_dir/server.yaml" > "$render_dir/server.namespaced.yaml"
mv "$render_dir/server.namespaced.yaml" "$render_dir/server.yaml"
for component in controller server; do
  {
    printf '%s\n' '# Generated by deploy/opensandbox/render.sh from the fixed chart upstream revision.'
    sed -e 's/app.kubernetes.io\/managed-by: Helm/app.kubernetes.io\/managed-by: kubectl/' -e 's/[[:space:]]*$//' "$render_dir/$component.yaml"
  } > "$root_dir/deploy/opensandbox/$component.yaml"
done
